package com.ecliptic.scanner

/**
 * Heuristic "build origin" analyzer: estimates whether a site was authored with the
 * help of an LLM / AI coding tool, from the shipped source. Two independent tiers:
 *
 *  1. PLATFORM fingerprint (high confidence) — AI *site builders* leave hard markers
 *     (script hosts, generator meta, data-* attributes, hosting domains). When one is
 *     found we name it: "Built with Lovable", etc.
 *  2. LLM COMMENT STYLE (soft, heuristic) — LLMs over-comment and reuse recognisable
 *     phrasings. Only meaningful on *unminified* source; minified bundles strip comments,
 *     so we say so honestly. We never claim a specific model (Claude vs GPT vs …): that
 *     is not reliably recoverable from shipped code.
 *
 * Output is evidence-first: the matched markers/phrases are returned so the UI can show
 * *why*. No vanity score — a plain confidence band (low/medium/high) and a caveat line.
 */
object BuildOriginAnalyzer {

    enum class Verdict { PLATFORM, HEAVY, MIXED, MINIMAL, INCONCLUSIVE }

    data class BuildOrigin(
        val verdict: Verdict,
        val label: String,
        val confidence: String,                    // "high" / "medium" / "low" / "n/a"
        val platform: String? = null,              // tier-1 builder name, if any
        val minified: Boolean = false,
        val commentCount: Int = 0,
        val llmSignalCount: Int = 0,
        val evidence: List<String> = emptyList(),  // human-readable matched markers
        val note: String = "",
        val analyzedJs: Boolean = false,           // bundled JS bodies were included
    )

    // ── Tier 1: AI site-builder platform fingerprints ────────────────────────
    // name → case-insensitive substrings; any hit = that platform. Ordered most-specific.
    private val PLATFORMS: List<Pair<String, List<String>>> = listOf(
        "Lovable" to listOf("gptengineer.js", "cdn.gpteng.co", "gpteng.co", "lovable-tagger", "data-lovable", ".lovable.app", "lovable.dev"),
        "v0 by Vercel" to listOf("generated by v0", "v0.dev", "v0-generated"),
        "bolt.new" to listOf("bolt.new", "stackblitz.com/edit"),
        "Replit Agent" to listOf("replit-badge", ".replit.dev", ".repl.co", "replit.com/@", "data-replit"),
        "Framer" to listOf("framerusercontent.com", "framer.com/m/", "content=\"framer"),
        "Durable" to listOf("durable.co", "madewithdurable"),
        "Wix ADI" to listOf("wix-adi", "static.wixstatic.com", "_wixcssimports"),
        "Softr" to listOf("softr.io", "softr-site"),
        "Builder.io" to listOf("cdn.builder.io", "data-builder-component"),
    )

    // ── Tier 2: LLM comment-style telltales ──────────────────────────────────
    // Phrases disproportionately common in LLM-written code comments. Matched inside
    // extracted comments only (never arbitrary page text), case-insensitive.
    private val LLM_PHRASES = listOf(
        "in a real app", "in a real-world", "in a production", "for now,", "for now we",
        "you would typically", "you'd typically", "this is a placeholder", "placeholder for",
        "for demonstration", "for simplicity", "as an example", "example usage",
        "feel free to", "make sure to", "don't forget to", "note that", "note:",
        "here we", "here's how", "we'll ", "we need to", "we can ",
        "this function", "this component", "this method", "helper function",
        "this ensures", "replace this with", "if needed", "if necessary",
        "todo:", "fixme:", "in practice", "under the hood",
    )

    // Short "obvious" comments LLMs add over trivial lines (strong signal when frequent):
    // a comment that is just a verb phrase re-describing the next line of code.
    private val OBVIOUS_COMMENT = Regex(
        """(?i)^(get|set|create|update|delete|render|fetch|loop through|initialize|define|check if|return|handle|add|remove|toggle|map over|filter|calculate|build|generate|parse|validate|convert|format|display|show|hide)\b.{0,48}$"""
    )

    private val EMOJI = Regex("[\\x{1F300}-\\x{1FAFF}\\x{2600}-\\x{27BF}\\x{2B00}-\\x{2BFF}]")

    // `//` line comments, but not inside URLs (`://`). Block + HTML comments too.
    private val COMMENT_LINE = Regex("""(?m)(?<![:/])//[^\n]{0,280}""")
    private val COMMENT_BLOCK = Regex("""/\*(.*?)\*/""", RegexOption.DOT_MATCHES_ALL)
    private val COMMENT_HTML = Regex("""<!--(.*?)-->""", RegexOption.DOT_MATCHES_ALL)
    private val JSDOC = Regex("""@(param|returns?|example|description)\b""")

    /**
     * @param text   source to analyze (HTML + response-header text, plus bundled JS when [analyzedJs]).
     * @param analyzedJs whether bundled script bodies were fetched and included in [text].
     */
    fun analyze(text: String, analyzedJs: Boolean = false): BuildOrigin {
        if (text.isBlank()) {
            return BuildOrigin(Verdict.INCONCLUSIVE, "No source to analyze", "n/a",
                note = "Scan a site first.", analyzedJs = analyzedJs)
        }
        val lower = text.lowercase()

        // ── Tier 1: platform ───────────────────────────────────────────────
        for ((name, needles) in PLATFORMS) {
            val hit = needles.firstOrNull { lower.contains(it) }
            if (hit != null) {
                return BuildOrigin(
                    verdict = Verdict.PLATFORM,
                    label = "Built with $name (AI site builder)",
                    confidence = "high",
                    platform = name,
                    evidence = listOf("marker: $hit"),
                    note = "Identified from a hard platform marker in the shipped page.",
                    analyzedJs = analyzedJs,
                )
            }
        }

        // ── Tier 2: comment-style heuristic ─────────────────────────────────
        val comments = buildList {
            COMMENT_LINE.findAll(text).take(600).forEach { add(it.value.removePrefix("//").trim()) }
            COMMENT_BLOCK.findAll(text).take(400).forEach { add(it.groupValues[1].trim()) }
            COMMENT_HTML.findAll(text).take(200).forEach { add(it.groupValues[1].trim()) }
        }.filter { it.length in 2..400 }

        val commentCount = comments.size
        val nonBlankLines = text.lineSequence().count { it.isNotBlank() }.coerceAtLeast(1)
        val avgLineLen = text.length.toDouble() / text.lineSequence().count().coerceAtLeast(1)
        // Minified if the body is long but has very few lines / huge average line length,
        // and almost no comments survived.
        val minified = text.length > 4000 && (avgLineLen > 300 || nonBlankLines < 12) && commentCount < 4

        if (minified) {
            return BuildOrigin(
                verdict = Verdict.INCONCLUSIVE,
                label = "Source minified, comment analysis unavailable",
                confidence = "n/a",
                minified = true,
                commentCount = commentCount,
                note = if (analyzedJs) "Bundled JS is minified, stripping comments. Platform markers (if any) would still show above."
                       else "Shipped code is minified. Try \"Analyze bundled JS\" — some builds ship readable source.",
                analyzedJs = analyzedJs,
            )
        }

        val matchedPhrases = LinkedHashSet<String>()
        var signal = 0
        var obvious = 0
        var emojiComments = 0
        var jsdoc = 0
        for (c in comments) {
            val cl = c.lowercase()
            var perComment = 0
            for (p in LLM_PHRASES) {
                if (cl.contains(p) && perComment < 3) { matchedPhrases.add(p); perComment++; signal++ }
            }
            if (OBVIOUS_COMMENT.containsMatchIn(c)) { obvious++; signal++ }
            if (EMOJI.containsMatchIn(c)) { emojiComments++; signal++ }
            if (JSDOC.containsMatchIn(c)) jsdoc++
        }
        if (jsdoc >= 4) signal += (jsdoc / 4)

        val commentDensity = commentCount.toDouble() / nonBlankLines

        val verdict = when {
            signal >= 12 || (signal >= 6 && commentDensity >= 0.12) -> Verdict.HEAVY
            signal >= 3 -> Verdict.MIXED
            else -> Verdict.MINIMAL
        }

        val evidence = buildList {
            matchedPhrases.take(8).forEach { add("phrase: “$it”") }
            if (obvious > 0) add("$obvious obvious one-line comment${if (obvious == 1) "" else "s"}")
            if (emojiComments > 0) add("$emojiComments comment${if (emojiComments == 1) "" else "s"} with emoji")
            if (jsdoc >= 4) add("$jsdoc JSDoc blocks")
            add("$commentCount comments over $nonBlankLines non-blank lines")
        }

        val (label, confidence) = when (verdict) {
            Verdict.HEAVY   -> "Appears heavily LLM-developed" to "medium"
            Verdict.MIXED   -> "Mixed codebase, some LLM-assisted markers" to "low"
            Verdict.MINIMAL -> "Minimal LLM comment markers" to "low"
            else            -> "Inconclusive" to "n/a"
        }

        return BuildOrigin(
            verdict = verdict,
            label = label,
            confidence = confidence,
            minified = false,
            commentCount = commentCount,
            llmSignalCount = signal,
            evidence = evidence,
            note = "Heuristic from code-comment style. Not a verdict, and it can't identify which model (Claude / GPT / etc.).",
            analyzedJs = analyzedJs,
        )
    }
}
